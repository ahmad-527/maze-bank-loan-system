import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.*;
import java.util.Arrays;

/** Embedded file database only: no Oracle connection, TCP server or web console is started. */
final class Database {
  private final String url;

  Database(Path directory) {
    try {
      Path root = directory.toAbsolutePath().normalize();
      if (root.toString().contains(";")
          || root.toString().contains("\n")
          || root.toString().contains("\r"))
        throw new IllegalArgumentException(
            "Choose a data-folder path without semicolons or newlines.");
      Files.createDirectories(root);
      url =
          "jdbc:h2:file:"
              + root.resolve("maze-bank").toString().replace('\\', '/')
              + ";DB_CLOSE_ON_EXIT=FALSE;LOCK_TIMEOUT=5000";
      Class.forName("org.h2.Driver");
      initialise();
    } catch (java.io.IOException | ClassNotFoundException | SQLException failure) {
      throw new IllegalStateException(
          "The local demo database could not be opened. Check its folder and close another running"
              + " copy.",
          failure);
    }
  }

  Connection open() throws SQLException {
    return DriverManager.getConnection(url, "sa", "");
  }

  private void initialise() throws SQLException {
    try (Connection connection = open();
        Statement statement = connection.createStatement()) {
      statement.execute(
          "CREATE TABLE IF NOT EXISTS app_meta(name VARCHAR(50) PRIMARY KEY, schema_value"
              + " VARCHAR(100) NOT NULL)");
      try (ResultSet version =
          statement.executeQuery("SELECT schema_value FROM app_meta WHERE name='schema_version'")) {
        if (version.next() && !version.getString(1).equals("1"))
          throw new SQLException("Unsupported schema version; no destructive migration attempted.");
      }
      statement.execute(
          "CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
              + " username VARCHAR(30) NOT NULL UNIQUE, mobile VARCHAR(30) NOT NULL, demo_reference"
              + " VARCHAR(30) NOT NULL, password_hash VARCHAR(200) NOT NULL, role VARCHAR(10) NOT"
              + " NULL CHECK(role IN ('CUSTOMER','ADMIN')))");
      statement.execute(
          "CREATE TABLE IF NOT EXISTS loan_applications(id BIGINT GENERATED BY DEFAULT AS IDENTITY"
              + " PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), full_name VARCHAR(120)"
              + " NOT NULL, email VARCHAR(200) NOT NULL, amount DECIMAL(15,3) NOT NULL"
              + " CHECK(amount>0), loan_type VARCHAR(40) NOT NULL, term_months INT NOT NULL,"
              + " purpose VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT"
              + " CURRENT_TIMESTAMP)");
      statement.execute(
          "CREATE TABLE IF NOT EXISTS questions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY"
              + " KEY, user_id BIGINT NOT NULL REFERENCES users(id), description VARCHAR(2000) NOT"
              + " NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
      statement.execute(
          "MERGE INTO app_meta(name,schema_value) KEY(name) VALUES('schema_version','1')");
      try (ResultSet count = statement.executeQuery("SELECT COUNT(*) FROM users")) {
        count.next();
        if (count.getInt(1) == 0) seed(connection);
      }
    }
  }

  private void seed(Connection connection) throws SQLException {
    connection.setAutoCommit(false);
    try {
      // Deliberately public, fictional walkthrough accounts; see README, not production secrets.
      long customer =
          seedAccount(connection, "demo-user", "DemoUser!2026", "CUSTOMER", "DEMO-0000");
      seedAccount(connection, "demo-admin", "DemoAdmin!2026", "ADMIN", "DEMO-STAFF");
      try (PreparedStatement insert =
          connection.prepareStatement(
              "INSERT INTO"
                  + " loan_applications(user_id,full_name,email,amount,loan_type,term_months,purpose)"
                  + " VALUES(?,?,?, ?,?,?,?)")) {
        insert.setLong(1, customer);
        insert.setString(2, "Demo Customer");
        insert.setString(3, "demo@example.invalid");
        insert.setBigDecimal(4, new java.math.BigDecimal("1250.500"));
        insert.setString(5, "Personal loan");
        insert.setInt(6, 12);
        insert.setString(7, "Fictional example for the portfolio walkthrough.");
        insert.executeUpdate();
      }
      try (PreparedStatement insert =
          connection.prepareStatement("INSERT INTO questions(user_id,description) VALUES(?,?)")) {
        insert.setLong(1, customer);
        insert.setString(2, "Fictional query: where can I review my submitted application?");
        insert.executeUpdate();
      }
      connection.commit();
    } catch (SQLException | RuntimeException failure) {
      connection.rollback();
      throw failure;
    } finally {
      connection.setAutoCommit(true);
    }
  }

  private long seedAccount(
      Connection connection, String username, String password, String role, String reference)
      throws SQLException {
    char[] chars = password.toCharArray();
    try (PreparedStatement insert =
        connection.prepareStatement(
            "INSERT INTO users(username,mobile,demo_reference,password_hash,role)"
                + " VALUES(?,?,?,?,?)",
            Statement.RETURN_GENERATED_KEYS)) {
      insert.setString(1, username);
      insert.setString(2, "00000000");
      insert.setString(3, reference);
      insert.setString(4, PasswordHasher.hash(chars));
      insert.setString(5, role);
      insert.executeUpdate();
      try (ResultSet keys = insert.getGeneratedKeys()) {
        keys.next();
        return keys.getLong(1);
      }
    } finally {
      Arrays.fill(chars, '\0');
    }
  }
}
